"""Таблица ладов и имён нот — собственный источник истины гармонического слоя.

Статическая замена таблицы удаляемой библиотеки: 8 канонических
семиступенных ладов (все дают терцовые аккорды min/maj/dim — условие
валидации :meth:`src.harmony.harmony.Harmony.set_scale`) плюс алиасы
``ionian`` (= major) и ``maj7`` (= mixolydian), сохранённые из прежнего
набора имён, чтобы поведение ``set_scale`` не изменилось.

Имена нот с альтерациями резолвятся в pitch class 0–11. Имена с октавой
(``"A4"``) и составные (``"A dorian"``) не поддерживаются — они
отклоняются как незнакомые.

Модуль — чистые данные и функции, без классов; импортирует только
stdlib и не зависит от :mod:`src.harmony.harmony` (обратная связь:
harmony импортирует scales, цикл запрещён).
"""

from __future__ import annotations

__all__ = [
    "ROOT_PITCH_CLASSES",
    "SCALES",
    "resolve_scale",
]

# Полутона от тоники для канонических диатонических ладов.
SCALES: dict[str, tuple[int, ...]] = {
    "major": (0, 2, 4, 5, 7, 9, 11),
    "dorian": (0, 2, 3, 5, 7, 9, 10),
    "phrygian": (0, 1, 3, 5, 7, 8, 10),
    "lydian": (0, 2, 4, 6, 7, 9, 11),
    "mixolydian": (0, 2, 4, 5, 7, 9, 10),
    "aeolian": (0, 2, 3, 5, 7, 8, 10),
    "locrian": (0, 1, 3, 5, 6, 8, 10),
    "minor": (0, 2, 3, 5, 7, 8, 10),
}

# Алиасы прежнего набора имён указывают на те же кортежи, что и
# канонические имена: добавляются после литерала, чтобы не дублировать
# значения.
SCALES["ionian"] = SCALES["major"]
SCALES["maj7"] = SCALES["mixolydian"]

# Имя ноты (с альтерациями) -> pitch class 0-11. Порядок — хроматическая
# гамма: для каждой ступени сначала диез, затем бемоль.
ROOT_PITCH_CLASSES: dict[str, int] = {
    "C": 0,
    "C#": 1,
    "Db": 1,
    "D": 2,
    "D#": 3,
    "Eb": 3,
    "E": 4,
    "F": 5,
    "F#": 6,
    "Gb": 6,
    "G": 7,
    "G#": 8,
    "Ab": 8,
    "A": 9,
    "A#": 10,
    "Bb": 10,
    "B": 11,
}


def resolve_scale(name: str) -> tuple[int, ...]:
    """Резолвить имя лада в кортеж полутонов от тоники.

    Args:
        name: Имя лада из таблицы (каноническое или алиас, например
            ``"major"``, ``"dorian"``, ``"ionian"``, ``"maj7"``).

    Returns:
        Кортеж полутонов (например, дорийский ``(0, 2, 3, 5, 7, 9, 10)``).

    Raises:
        ValueError: Если имени нет в таблице.
    """
    try:
        return SCALES[name]
    except KeyError as exc:
        raise ValueError(f"Неизвестный лад: {name!r}") from exc
