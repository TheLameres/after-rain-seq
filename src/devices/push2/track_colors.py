"""Палитра цветов дорожек (запрос 02.11.2026, п. 3).

Каждая дорожка получает свой цвет — детерминированно, по абсолютному
индексу в сессии (порядок создания). Цвета вычислены ``rgb_to_bgr565``
(тот же слой devices/push2) — 12 различимых на дисплее Push 2 оттенков,
соседние индексы контрастны.

Использование: ``TrackRowView.color``/``TrackDetailView.color``/
``TrackMacroView.color`` — цветной маркер в списке TRACKS и полоса
на экранах GEN/MACRO.
"""

from __future__ import annotations

from src.devices.push2.renderer import rgb_to_bgr565

# (R, G, B) — подобраны вручную: тёплые/холодные чередуются.
_TRACK_RGB: tuple[tuple[int, int, int], ...] = (
    (255, 70, 70),  # красный
    (70, 220, 90),  # зелёный
    (80, 130, 255),  # синий
    (255, 220, 60),  # жёлтый
    (255, 90, 220),  # маджента
    (60, 225, 225),  # циан
    (255, 150, 50),  # оранжевый
    (255, 140, 170),  # розовый
    (160, 240, 70),  # лайм
    (170, 100, 255),  # фиолетовый
    (255, 240, 150),  # светло-жёлтый
    (60, 90, 210),  # тёмно-синий
)

TRACK_COLORS: tuple[int, ...] = tuple(rgb_to_bgr565(r, g, b) for r, g, b in _TRACK_RGB)


def track_color(index: int) -> int:
    """Цвет дорожки по абсолютному индексу в сессии (по кругу)."""
    return TRACK_COLORS[index % len(TRACK_COLORS)]
