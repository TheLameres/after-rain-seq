"""Палитра LED Push 2 — 128 записей, снятых с устройства (план §3.2б).

Почему этот модуль вообще существует: пэды Push 2 адресуются **индексом
палитры 0..127**, а не RGB. Пока в проекте был только BGR565 для дисплея,
цвет дорожки физически не мог подсветить пэд — нечем было получить индекс.
Здесь лежит соответствие «индекс → RGB», снятое с живого устройства
через sysex ``0x04`` (Get LED Color Palette Entry).

Структура палитры (спецом не документирована, обнаружена разбором данных):

    индексы   0        — чёрный (синоним «выключено»)
    индексы   1– 64    — яркий ряд, V 0.29..1.00
    индексы  65–116    — тёмный ряд, V 0.05..0.40 (всегда приглушён)
    индексы 117–127    — серая шкала и чистые RGB-крайности

Гипотеза «индекс +64 = затемнённый близнец того же оттенка» проверена и
**опровергнута**: совпадение оттенка только у 10 из 52 пар. Ряды
независимы, поэтому тёмный ряд нельзя использовать как «выключенное»
состояние того же цвета.

Источник значений: публичный дамп палитры (``indexRGB.txt``, Cycling '74
Max For Live forum, 2016), сверенный по якорям официальной спецификации
Ableton Push 2 MIDI & Display Interface: индексы 0/117 = (0,0,0),
118/121 = (89,89,89), 125 = (0,0,255), 126 = (0,255,0), 127 = (255,0,0).
"""

