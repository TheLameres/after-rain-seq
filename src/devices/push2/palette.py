def rgb(index: int) -> tuple[int, int, int]:
    """RGB-тройка записи палитры.

    Аргументы:
        index: Индекс палитры 0..127.

    Raises:
        IndexError: Если индекс вне 0..127. Молча заворачивать по модулю
            нельзя — это скрыло бы ошибку адресации пэда.
    """
    if not 0 <= index < len(PALETTE):
        raise IndexError(f"Индекс палитры {index} вне диапазона 0..{len(PALETTE) - 1}")
    return PALETTE[index]


def bgr565(index: int) -> int:
    """Запись палитры, упакованная в BGR565 для дисплея Push 2."""
    r, g, b = rgb(index)
    return ((b >> 3) << 11) | ((g >> 2) << 5) | (r >> 3)


#: 16 цветов дорожек — по одному на ``MAX_TRACKS``, порядок по кругу оттенков,
#: чтобы соседние дорожки различались максимально.
#:
#: Отбор: пул записей с V >= 0.55 и S >= 0.40 (40 штук), затем greedy
#: farthest-point в CIE L*a*b* **после** квантования в BGR565 —
#: минимальная ΔE внутри набора 38.6. Ограничение пула по яркости
#: принципиально: отбор только по ΔE дал 6 тёмных и блёклых цветов из 16,
#: которые на пэде неотличимы от погашенного.
